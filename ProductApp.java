    private void btnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessActionPerformed
        // TODO add your handling code here:
        
        // 1. Capture customer name
        String name = txtCustomerName.getText().trim();
        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter the customer name.");
            return;
        }

        String product = (String) cmbProduct.getSelectedItem();

        double price;
        try {
            price = Double.parseDouble(txtPrice.getText().trim().replace(',', '.'));
            if (price <= 0) throw new NumberFormatException();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Please enter a valid price greater than 0.");
            return;
        }

        //Calculations
        double vat = price * VAT_RATE;
        double commission = price * COMMISSION_RATE;
        double total = price + vat + commission;

        String result = String.format(Locale.US,
            "Customer Name: %s%n" +
            "Product: %s%n" +
            "Price: R%.2f%n" +
            "VAT Amount (15%%): R%.2f%n" +
            "Commission Amount (5%%): R%.2f%n" +
            "Total Sale Amount: R%.2f%n",
            name, product, price, vat, commission, total);

        //Show on screen
        txtOutput.setText(result);

        // 5. Save to file.txt (append so earlier sales are kept)
        try (PrintWriter out = new PrintWriter(new FileWriter("file.txt", true))) {
            out.println(result);
            out.println("----------------------------------------");
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "Could not save to file.txt: " + ex.getMessage());
        }
    }

